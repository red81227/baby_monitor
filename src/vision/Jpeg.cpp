bool ensureHuffmanTables(std::vector<unsigned char>& jpeg) {
    if (jpeg.size() < 4 || jpeg[0] != 0xFF || jpeg[1] != 0xD8) return false;

    // 逐一走過 SOS 之前的標記段
    std::size_t i = 2;
    while (i + 4 <= jpeg.size()) {
        if (jpeg[i] != 0xFF) return false;  // 結構不對就不動它
        const unsigned char marker = jpeg[i + 1];
        if (marker == 0xFF) {  // 填充位元組
            ++i;
            continue;
        }
        if (marker == 0xC4) return false;  // 已有 DHT
        if (marker == 0xDA) {              // SOS：在它前面插入標準 DHT
            const auto seg = standardDhtSegment();
            jpeg.insert(jpeg.begin() + static_cast<std::ptrdiff_t>(i), seg.begin(), seg.end());
            return true;
        }
        const std::size_t len = (static_cast<std::size_t>(jpeg[i + 2]) << 8) | jpeg[i + 3];
        if (len < 2) return false;
        i += 2 + len;
    }
    return false;
}

int reducedDecodeFactor(int width, int height) {
    const int longSide = std::max(width, height);
    if (longSide < 1280) return 1;
    int factor = 1;
    for (int f : {2, 4, 8}) {
        if (longSide / f >= 640) factor = f;
    }
    return factor;
}
