std::vector<unsigned char> standardDhtSegment() {
    std::vector<unsigned char> body;
    for (const auto& [p, n] : {std::pair{kDcLum, sizeof(kDcLum)}, std::pair{kAcLum, sizeof(kAcLum)},
                               std::pair{kDcChr, sizeof(kDcChr)}, std::pair{kAcChr, sizeof(kAcChr)}}) {
        body.insert(body.end(), p, p + n);
    }
    const std::size_t len = body.size() + 2;  // 長度欄位含自己的 2 bytes
    std::vector<unsigned char> seg{0xFF, 0xC4, static_cast<unsigned char>(len >> 8),
                                   static_cast<unsigned char>(len & 0xFF)};
    seg.insert(seg.end(), body.begin(), body.end());
    return seg;
}

